#!/usr/bin/env node
/**
 * Builds every visual from profile.json + data/github.json:
 *   assets/svg/*.svg          dark and light section components
 *   src/css/tokens.generated.css
 *   src/js/profile-data.js
 *   README.md
 *
 * No dependencies. Run `node scripts/build.mjs` after editing the config.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokens } from './lib/theme.mjs';
import { renderHero } from './lib/svg/hero.mjs';
import { renderSocialsHeader, renderSocialCard } from './lib/svg/socials.mjs';
import { renderAbout } from './lib/svg/about.mjs';
import { renderStack } from './lib/svg/stack.mjs';
import { renderProjectsHeader, renderProject } from './lib/svg/projects.mjs';
import { renderStats } from './lib/svg/stats.mjs';
import { renderActivity } from './lib/svg/activity.mjs';
import { renderFooter } from './lib/svg/footer.mjs';
import { escapeXml, formatDate } from './lib/util.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'assets', 'svg');
const readJson = async (file) => JSON.parse(await fs.readFile(path.join(ROOT, file), 'utf8'));

const profile = await readJson('profile.json');
const github = await readJson('data/github.json');
const MODES = ['dark', 'light'];
const written = [];

async function write(rel, content) {
  const file = path.join(ROOT, rel);
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, content);
  written.push({ rel, bytes: Buffer.byteLength(content) });
}

await fs.mkdir(OUT, { recursive: true });

for (const mode of MODES) {
  const t = tokens(profile.palette, mode);
  const svg = {
    hero: renderHero(t, profile),
    socials: renderSocialsHeader(t, profile.socialsSection),
    about: renderAbout(t, profile.about),
    stack: renderStack(t, profile.stack),
    projects: renderProjectsHeader(t, profile.projects),
    stats: renderStats(t, profile.stats, github),
    activity: renderActivity(t, profile.activity, github),
    footer: renderFooter(t, profile.footer)
  };

  for (const [name, content] of Object.entries(svg)) {
    await write(`assets/svg/${name}-${mode}.svg`, content);
  }

  for (const [index, social] of profile.socials.entries()) {
    await write(`assets/svg/social-${social.id}-${mode}.svg`, renderSocialCard(t, social, index));
  }

  for (const [index, project] of profile.projects.items.entries()) {
    const meta = github.projects?.find((p) => p.id === project.id) || null;
    await write(
      `assets/svg/project-${project.id}-${mode}.svg`,
      renderProject(t, project, meta, index, profile.projects.items.length)
    );
  }
}

await write('src/css/tokens.generated.css', generateTokens(profile));
await write('src/js/profile-data.js', generateProfileData(profile, github));
await write('assets/icons/favicon.svg', generateFavicon(profile));
await write('README.md', generateReadme(profile, github));

report();

function generateTokens(cfg) {
  const dark = tokens(cfg.palette, 'dark');
  const light = tokens(cfg.palette, 'light');
  const vars = (t) => [
    `--bg: ${t.background};`,
    `--bg-alt: ${t.backgroundAlt};`,
    `--surface: ${t.surface};`,
    `--surface-alt: ${t.surfaceAlt};`,
    `--accent: ${t.accent};`,
    `--accent-bright: ${t.accentBright};`,
    `--accent-deep: ${t.accentDeep};`,
    `--text: ${t.text};`,
    `--text-muted: ${t.textMuted};`,
    `--text-faint: ${t.textFaint};`,
    `--border: ${t.border};`,
    `--border-strong: ${t.borderStrong};`,
    `--hairline: ${t.hairline};`,
    `--chip-bg: ${t.chipBg};`,
    `--chip-border: ${t.chipBorder};`,
    `--glow: ${t.glow};`,
    `--shadow: ${t.shadow};`,
    `--card-1: ${t.card1};`,
    `--card-2: ${t.card2};`,
    `--sheen: ${t.sheen};`,
    ...t.heat.map((color, i) => `--heat-${i}: ${color};`),
    ...t.languageColors.map((color, i) => `--lang-${i}: ${color};`)
  ].join('\n  ');

  return `/* Generated by scripts/build.mjs from profile.json — do not edit by hand. */
:root {
  color-scheme: dark;
  ${vars(dark)}
}

[data-theme="light"] {
  color-scheme: light;
  ${vars(light)}
}
`;
}

function generateProfileData(cfg, data) {
  return `/* Generated by scripts/build.mjs from profile.json + data/github.json. */
export const PROFILE = ${JSON.stringify(cfg, null, 2)};
export const GITHUB = ${JSON.stringify(data, null, 2)};
export const BUILD_TIME = ${JSON.stringify(new Date().toISOString())};
`;
}

function generateFavicon(cfg) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64">
  <defs>
    <linearGradient id="favicon" x1="0" y1="0" x2="1" y2="1">
      <stop stop-color="${cfg.palette.dark.accentBright}"/>
      <stop offset="1" stop-color="${cfg.palette.dark.accentDeep}"/>
    </linearGradient>
  </defs>
  <rect width="64" height="64" rx="18" fill="${cfg.palette.dark.background}"/>
  <rect x="0.5" y="0.5" width="63" height="63" rx="17.5" fill="none" stroke="${cfg.palette.dark.accent}" stroke-opacity="0.28"/>
  <text x="32" y="45" text-anchor="middle" font-family="'Segoe UI', 'Helvetica Neue', Arial, sans-serif" font-size="36" font-weight="800" fill="url(#favicon)">S</text>
  <circle cx="48" cy="16" r="2.4" fill="${cfg.palette.dark.accentBright}"/>
</svg>
`;
}

function picture(base, alt, { width = '100%' } = {}) {
  return `<picture>
  <source media="(prefers-color-scheme: dark)" srcset="${base}-dark.svg">
  <source media="(prefers-color-scheme: light)" srcset="${base}-light.svg">
  <img src="${base}-dark.svg" width="${width}" alt="${escapeXml(alt)}">
</picture>`;
}

function generateReadme(cfg, data) {
  const visible = (id) => cfg.sections.visible?.[id] !== false;
  const blocks = [];
  const projectMeta = new Map((data.projects || []).map((p) => [p.id, p]));

  for (const id of cfg.sections.order) {
    if (!visible(id)) continue;
    if (id === 'hero') {
      blocks.push(picture('assets/svg/hero', `${cfg.identity.name} — ${cfg.identity.role} / ${cfg.identity.subrole}. ${cfg.identity.description}`));
    }
    if (id === 'socials') {
      const cards = cfg.socials
        .map(
          (social) => `<a href="${social.url}"><picture>
  <source media="(prefers-color-scheme: dark)" srcset="assets/svg/social-${social.id}-dark.svg">
  <source media="(prefers-color-scheme: light)" srcset="assets/svg/social-${social.id}-light.svg">
  <img src="assets/svg/social-${social.id}-dark.svg" width="271" alt="${escapeXml(`${social.label} — ${social.handle}`)}">
</picture></a>`
        )
        .join('\n');
      blocks.push(`${picture('assets/svg/socials', cfg.socialsSection.title + '. ' + cfg.socialsSection.note)}

<p align="center">
${cards}
</p>`);
    }
    if (id === 'about') {
      blocks.push(picture('assets/svg/about', `${cfg.about.title}. ${cfg.about.cards.map((c) => `${c.title}: ${c.text}`).join(' ')}`));
    }
    if (id === 'stack') {
      blocks.push(picture('assets/svg/stack', `${cfg.stack.title}: ${cfg.stack.groups.map((g) => `${g.label} — ${g.items.map((i) => i.label).join(', ')}`).join('. ')}`));
    }
    if (id === 'projects') {
      const items = cfg.projects.items.map((project) => {
        const meta = projectMeta.get(project.id);
        const stars = meta && Number.isFinite(meta.stars) ? meta.stars : null;
        return `<a href="${project.repo}"><picture>
  <source media="(prefers-color-scheme: dark)" srcset="assets/svg/project-${project.id}-dark.svg">
  <source media="(prefers-color-scheme: light)" srcset="assets/svg/project-${project.id}-light.svg">
  <img src="assets/svg/project-${project.id}-dark.svg" width="100%" alt="${escapeXml(`${project.name} — ${project.category}. ${project.description}${stars === null ? '' : ` ${stars} stars.`} Open the repository.`)}">
</picture></a>`;
      });
      blocks.push(`${picture('assets/svg/projects', `${cfg.projects.title}. ${cfg.projects.note}`)}
${items.join('\n\n')}`);
    }
    if (id === 'stats') {
      blocks.push(picture('assets/svg/stats', `GitHub statistics for ${cfg.stats.username}: ${data.stats.stars} stars, ${data.stats.repos} public repositories, ${data.stats.followers} followers, ${data.stats.contributions} contributions in the last year.`));
    }
    if (id === 'activity') {
      const langs = data.languages || [];
      const top = langs.slice(0, 4);
      const other = Math.round(langs.slice(4).reduce((n, l) => n + l.percent, 0) * 10) / 10;
      const summary = [...top.map((l) => `${l.name} ${l.percent}%`), other ? `Other ${other}%` : null].filter(Boolean).join(', ');
      blocks.push(picture('assets/svg/activity', `Contribution activity: ${data.stats.contributions} contributions in the last year. Top languages: ${summary}.`));
    }
    if (id === 'footer') {
      blocks.push(`${picture('assets/svg/footer', `${cfg.footer.line} ${cfg.footer.note}`)}
<p><sub><a href="${cfg.meta.siteUrl}">Open the interactive profile</a> &nbsp;·&nbsp; <a href="${cfg.meta.repoUrl}">Source</a> &nbsp;·&nbsp; <a href="SETUP.md">Setup &amp; docs</a></sub></p>`);
    }
  }

  return `<!-- Generated by scripts/build.mjs from profile.json. Edit the config, then run npm run build. -->
<div align="center">

${blocks.join('\n\n')}

</div>
`;
}

function report() {
  const total = written.reduce((n, f) => n + f.bytes, 0);
  for (const file of written) {
    console.log(`${(file.bytes / 1024).toFixed(1).padStart(7)} KB  ${file.rel}`);
  }
  console.log(`\n[build] ${written.length} files, ${(total / 1024).toFixed(0)} KB total · data from ${formatDate(github.generatedAt)}`);
}
